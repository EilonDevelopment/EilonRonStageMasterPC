/**
 * Parse desktop protocol reference files into TypeScript RF templates.
 * Source: PROTOCOLO CONFIG CRR FROM PC (2.4 / 900 baud tables).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DESKTOP = 'C:/Users/Moshe/Desktop/PROTOCOLO CONFIG CRR FROM PC';

function parse24File(text) {
  const out = {};
  const sections = text.split(/BAUDRATE\s*(?:=\s*)?([\d.]+)\s*:/gi);
  for (let i = 1; i < sections.length; i += 2) {
    const label = sections[i].trim();
    const body = sections[i + 1] ?? '';
    const bytes = [];
    for (const line of body.split(/\r?\n/)) {
      const m = line.match(/^\s*([0-9A-Fa-f]{1,2})\s*-/);
      if (m) bytes.push(parseInt(m[1], 16));
    }
    if (bytes.length > 0) out[label] = bytes;
  }
  return out;
}

function parse900ArrayBlock(block) {
  const bytes = [];
  const re = /0x([0-9A-Fa-f]{1,2})/g;
  let m;
  while ((m = re.exec(block)) !== null) {
    bytes.push(parseInt(m[1], 16));
  }
  return bytes;
}

function parse900File(text) {
  const out = {};
  const re = /data_arr_(?:rx|tx)_([\w.]+)\s*=\s*\{([\s\S]*?)\};/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    const key = m[1].replace('_', '.');
    const bytes = parse900ArrayBlock(m[2]);
    if (bytes.length > 0) out[key] = bytes;
  }
  return out;
}

function toTsBytes(name, map) {
  const entries = Object.entries(map)
    .map(([k, arr]) => `  '${k}': new Uint8Array([${arr.map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ')}]),`)
    .join('\n');
  return `export const ${name} = {\n${entries}\n} as const;\n`;
}

const cc24 = parse24File(readFileSync(join(DESKTOP, '2.4 Configurations according to baudRates.txt'), 'utf8'));
const si900raw = parse900File(readFileSync(join(DESKTOP, '900 Configurations according to baudRates.txt'), 'utf8'));

/** LabVIEW wire capture — golden CC24 register blocks (first 47 B per slot). */
function exampleSlotRegBlock(addrIndex) {
  const example = Buffer.from(
    readFileSync(join(DESKTOP, 'Example.txt'), 'utf8').trim(),
    'hex',
  );
  const HDR = 17;
  const SLOT = 367;
  const base = HDR + addrIndex * SLOT + 1;
  return Array.from(example.subarray(base, base + 47));
}

// Example uses PKTCTRL1=0x07 on wire; reference file lists 0x04. Prefer live capture bytes.
for (const bytes of Object.values(cc24)) {
  if (bytes[7] === 0x04) bytes[7] = 0x07;
  if (bytes[9] === 0xeb) bytes[9] = 0x00;
}
cc24['10'] = exampleSlotRegBlock(0);
cc24['100'] = exampleSlotRegBlock(1);

// Prefer tx templates; fall back to rx. Normalize keys to match UI baud labels.
const si900 = {};
for (const [k, v] of Object.entries(si900raw)) {
  const norm = k.replace('9.6', '9.6').replace('19.2', '19.2');
  if (k.startsWith('tx_') || !si900[norm]) {
    const label = k.replace(/^tx_/, '').replace(/^rx_/, '');
    if (!si900[label] || k.startsWith('tx_')) si900[label] = v;
  }
}

const baudKeys = ['10', '19.2', '38.4', '76.8', '100', '250', '500'];
for (const k of baudKeys) {
  if (!cc24[k]) console.warn('missing 2.4 template for baud', k);
  if (!si900[k] && !si900[k.replace('.', '_')]) {
    const alt = Object.keys(si900).find((x) => x.includes(k.replace('.', '')));
    if (alt) si900[k] = si900[alt];
  }
}

const ts = `/** Auto-generated by tools/generate-crr-rf-templates.mjs — do not edit by hand. */

export const CRR_CC24_BAUD_KEYS = ${JSON.stringify(baudKeys)} as const;
export type CrrCc24BaudKey = (typeof CRR_CC24_BAUD_KEYS)[number];

${toTsBytes('CRR_CC24_TEMPLATES_BY_BAUD', cc24)}
${toTsBytes('CRR_SI900_TEMPLATES_BY_BAUD', si900)}

export const CRR_SLOT_CONFIG_SIZE = 364;
export const CRR_SLOT_SIZE = 367;
export const CRR_CONFIG_HEADER_SIZE = 17;
`;

writeFileSync(join(ROOT, 'src/helper/crrRfTemplates.ts'), ts);
console.log('Wrote crrRfTemplates.ts — 2.4:', Object.keys(cc24).length, '900:', Object.keys(si900).length);
